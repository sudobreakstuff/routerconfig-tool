def lookup_vendor(mac: str) -> str:
    """Look up vendor from MAC OUI prefix."""
    if not mac:
        return ""
    clean = mac.replace(":", "").replace("-", "").replace(".", "").upper()[:6]
    if len(clean) < 6:
        return ""
    return OUI_DB.get(clean, "")
